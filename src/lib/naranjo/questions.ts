import type { CenterId, Instinct, SubtypeId, TypeId } from "./catalog";

export type Load = { key: string; weight: number };

export type Question = {
  id: string;
  stage: 1 | 2;
  text: string;
  help?: string;
  section: string;
  type?: TypeId;
  subtype?: SubtypeId;
  center?: CenterId;
  reverse?: boolean;
  kind?: "content" | "validity";
  facet?: "passion" | "fixation" | "center" | "check";
  pair?: string;
  loads: Load[];
};

const CENTER_OF: Record<TypeId, CenterId> = {
  1: "gut",
  2: "heart",
  3: "heart",
  4: "heart",
  5: "head",
  6: "head",
  7: "head",
  8: "gut",
  9: "gut",
};

function t(
  id: string,
  type: TypeId,
  text: string,
  extra?: Partial<Question>,
): Question {
  const reverse = extra?.reverse;
  const center = CENTER_OF[type];
  return {
    id,
    stage: 1,
    type,
    center,
    text,
    section: "mix",
    facet: extra?.facet ?? "passion",
    pair: extra?.pair ?? `t${type}-core`,
    reverse,
    kind: "content",
    loads: extra?.loads ?? [
      { key: `t${type}`, weight: 1 },
      { key: `c-${center}`, weight: reverse ? 0.25 : 0.35 },
    ],
    help: extra?.help,
  };
}

function s(
  id: string,
  subtype: SubtypeId,
  type: TypeId,
  instinct: Instinct,
  text: string,
): Question {
  return {
    id,
    stage: 2,
    subtype,
    type,
    text,
    section: "mix",
    kind: "content",
    loads: [
      { key: subtype, weight: 1 },
      { key: `t${type}`, weight: 0.25 },
      { key: instinct, weight: 0.35 },
    ],
  };
}

function c(id: string, center: CenterId, text: string): Question {
  return {
    id,
    stage: 1,
    center,
    text,
    section: "mix",
    kind: "content",
    facet: "center",
    loads: [{ key: `c-${center}`, weight: 1 }],
  };
}

function v(
  id: string,
  text: string,
  extra: { pair?: string; loads?: Load[]; reverse?: boolean },
): Question {
  return {
    id,
    stage: 1,
    text,
    section: "mix",
    kind: "validity",
    facet: "check",
    pair: extra.pair,
    reverse: extra.reverse,
    loads: extra.loads ?? [{ key: "valid", weight: 1 }],
  };
}

