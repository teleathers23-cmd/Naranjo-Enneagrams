import type { CenterId, Instinct, SubtypeId, TypeId } from "./catalog";

export type Load = { key: string; weight: number };

export type Question = {
  id: string;
  stage: 1 | 2;
  text: string;
  help?: string;
  section: string;
  type?: TypeId;
  subtype?: SubtypeId;
  center?: CenterId;
  reverse?: boolean;
  loads: Load[];
};

function t(
  id: string,
  type: TypeId,
  text: string,
  extra?: Partial<Question>,
): Question {
  return {
    id,
    stage: 1,
    type,
    text,
    section: `type-${type}`,
    loads: extra?.loads ?? [{ key: `t${type}`, weight: extra?.reverse ? -1 : 1 }],
    reverse: extra?.reverse,
    help: extra?.help,
  };
}

function s(
  id: string,
  subtype: SubtypeId,
  type: TypeId,
  instinct: Instinct,
  text: string,
  help?: string,
): Question {
  return {
    id,
    stage: 2,
    subtype,
    type,
    text,
    help,
    section: `sub-${type}`,
    loads: [
      { key: subtype, weight: 1 },
      { key: `t${type}`, weight: 0.25 },
      { key: instinct, weight: 0.35 },
    ],
  };
}

function c(id: string, center: CenterId, text: string, help?: string): Question {
  return {
    id,
    stage: 1,
    center,
    text,
    help,
    section: "center",
    loads: [{ key: `c-${center}`, weight: 1 }],
  };
}

