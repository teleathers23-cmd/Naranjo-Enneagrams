function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle<T>(arr: T[], rng: () => number): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function bucketKey(q: Question): string {
  if (q.kind === "validity") return `v-${q.id}`;
  if (q.type) return `t${q.type}`;
  if (q.center) return `c-${q.center}`;
  return q.id;
}

/** 按型号/中心分桶打散，避免同一号连在一起。每次种子都会得到不同顺序。 */
export function interleaveQuestions(qs: Question[], seed: number): Question[] {
  const rng = mulberry32(seed >>> 0 || 1);
  const remaining = shuffle(qs, rng);
  const out: Question[] = [];
  while (remaining.length) {
    const lastKey = out.length ? bucketKey(out[out.length - 1]!) : null;
    let idx = remaining.findIndex((q) => bucketKey(q) !== lastKey);
    if (idx < 0) idx = 0;
    out.push(remaining.splice(idx, 1)[0]!);
  }
  return out;
}

export function chunkQuestions(qs: Question[], size: number): Question[][] {
  const chunks: Question[][] = [];
  for (let i = 0; i < qs.length; i += size) chunks.push(qs.slice(i, i + size));
  return chunks;
}
